def fast_naive_prompt(
    query: str,
    context: str,
    available_source_ids: list[str],
) -> str:
    allowed = ", ".join(available_source_ids)
    return (
        "<QUESTION>\n"
        f"{query}\n"
        "</QUESTION>\n\n"
        f"Разрешённые источники: {allowed}.\n"
        "Используй только эти S-метки.\n\n"
        "<SOURCES>\n"
        f"{context}\n"
        "</SOURCES>"
    )


def context_grader_prompt(
    query: str,
    context: str,
    available_source_ids: list[str],
) -> str:
    allowed = ", ".join(available_source_ids)
    return (
        "<QUESTION>\n"
        f"{query}\n"
        "</QUESTION>\n\n"
        f"Разрешённые идентификаторы источников: {allowed}.\n"
        "Верни decision, relevant_source_ids, missing_information, "
        "rewritten_queries и reason.\n\n"
        "<SOURCES>\n"
        f"{context}\n"
        "</SOURCES>"
    )


def answer_generator_prompt(
    query: str,
    context: str,
    available_source_ids: list[str],
    feedback: list[str] | None = None,
) -> str:
    feedback_block = ""
    if feedback:
        feedback_block = (
            "\n\n<VALIDATION_FEEDBACK>\n- "
            + "\n- ".join(feedback)
            + "\n</VALIDATION_FEEDBACK>\n"
            "Исправь ошибки и сформируй ответ заново без объяснений."
        )

    allowed = ", ".join(available_source_ids)
    return (
        "<QUESTION>\n"
        f"{query}\n"
        "</QUESTION>\n\n"
        f"Разрешённые источники: {allowed}.\n"
        "Каждое фактическое предложение заканчивай подходящей S-меткой.\n"
        "used_source_ids должен совпадать с метками в answer."
        f"{feedback_block}\n\n"
        "<SOURCES>\n"
        f"{context}\n"
        "</SOURCES>"
    )


def answer_validator_prompt(query: str, context: str, answer: str) -> str:
    return (
        "<QUESTION>\n"
        f"{query}\n"
        "</QUESTION>\n\n"
        "<SOURCES>\n"
        f"{context}\n"
        "</SOURCES>\n\n"
        "<ANSWER>\n"
        f"{answer}\n"
        "</ANSWER>"
    )
